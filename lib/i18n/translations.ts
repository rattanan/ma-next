const thaiToEnglish = new Map<string, string>(translationPairs);
const englishToThai = new Map<string, string>(translationPairs.map(([th, en]) => [en, th]));

function preserveOuterWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function translateTemplate(text: string, locale: Locale) {
  const templates: Array<[RegExp, (matches: RegExpMatchArray) => string]> = locale === "en"
    ? [
        [/^พบ (\d+) บทความ$/, (m) => `Found ${m[1]} articles`],
        [/^(\d+) บทความ$/, (m) => `${m[1]} articles`],
        [/^หน้า (\d+) จาก (\d+)$/, (m) => `Page ${m[1]} of ${m[2]}`],
        [/^แสดง (\d+)-(\d+) จาก (\d+) รายการ$/, (m) => `Showing ${m[1]}-${m[2]} of ${m[3]} items`],
        [/^(\d+) รายการ$/, (m) => `${m[1]} items`],
        [/^(\d+) รายการที่รออนุมัติ$/, (m) => `${m[1]} pending approvals`],
        [/^คำอธิบายช่อง (.+)$/, (m) => `Help for ${m[1]}`],
      ]
    : [
        [/^Found (\d+) articles$/, (m) => `พบ ${m[1]} บทความ`],
        [/^(\d+) articles$/, (m) => `${m[1]} บทความ`],
        [/^Page (\d+) of (\d+)$/, (m) => `หน้า ${m[1]} จาก ${m[2]}`],
        [/^Showing (\d+)-(\d+) of (\d+) items$/, (m) => `แสดง ${m[1]}-${m[2]} จาก ${m[3]} รายการ`],
        [/^(\d+) items$/, (m) => `${m[1]} รายการ`],
        [/^(\d+) pending approvals$/, (m) => `${m[1]} รายการที่รออนุมัติ`],
        [/^(\d+) managed accounts$/, (m) => `บัญชีที่ดูแล ${m[1]} บัญชี`],
        [/^Help for (.+)$/, (m) => `คำอธิบายช่อง ${m[1]}`],
      ];

  for (const [pattern, format] of templates) {
    const match = text.match(pattern);
    if (match) return format(match);
  }
  return null;
}

export function translateUiText(source: string, locale: Locale): string {
  const text = source.trim();
  if (!text) return source;
  const direct = locale === "en" ? thaiToEnglish.get(text) : englishToThai.get(text);
  const translated = direct ?? translateTemplate(text, locale);
  return translated ? preserveOuterWhitespace(source, translated) : source;
}

export function isLocale(value: string | null): value is Locale {
  return value === "th" || value === "en";
}
